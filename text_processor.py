import re

STOP_WORDS = {
    "и", "в", "на", "с", "по", "для", "от", "до", "из", "к", "у", "о", "об",
    "за", "под", "над", "при", "без", "через", "между", "или", "но", "а",
    "что", "чтобы", "как", "так", "это", "весь", "все", "всех", "свой",
    "свои", "который", "которая", "которые", "которое", "быть", "был",
    "была", "было", "были", "есть", "не", "ни", "же", "ли", "бы"
}


def normalize_text(text: str) -> list[str]:
    """
    Нормализует текст: приводит к нижнему регистру, убирает пунктуацию,
    разбивает на слова и удаляет стоп-слова.

    Возвращает список очищенных слов.
    """
    if not text:
        return []

    text = text.strip()

    text = text.lower()

    text = re.sub(r'[^\w\s]', ' ', text)

    words = text.split()

    cleaned_words = [word for word in words if word not in STOP_WORDS and word != '']

    return cleaned_words